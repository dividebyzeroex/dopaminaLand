import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { isStoryReply, isExplicit, isGreeting, askMessage, alertHint, parseBrl, parseCommand, defaultTarget, buildTargetReply, parseComment, buildFoundReply, parseIncoming, parseRequest, verifySignature, SIGNATURE, DISCLAIMER } from "../src/lib/raiox-reply.ts";

const body = '{"a":1}';
const sig = createHmac("sha256", "s3").update(body).digest("hex");
assert.equal(verifySignature(body, sig, "s3"), true);
assert.equal(verifySignature(body, sig, "outro"), false);
assert.equal(verifySignature(body + " ", sig, "s3"), false);
assert.equal(verifySignature(body, null, "s3"), false);

const ev = (over = {}) => ({ id: "e1", event: "message.received", message: { conversationId: "c1", direction: "incoming", text: " raiox iPhone 15 ", sender: { id: "u1" } }, account: { accountId: "a1" }, metadata: {}, ...over });
assert.deepEqual(parseIncoming(ev()), { eventId: "e1", conversationId: "c1", accountId: "a1", senderId: "u1", text: "raiox iPhone 15", storyReply: false });
assert.equal(parseIncoming(ev({ event: "message.sent" })), null);
assert.equal(parseIncoming(ev({ metadata: { standby: true } })), null);
assert.equal(parseIncoming(ev({ message: { conversationId: "c1", direction: "outgoing", text: "oi" } })), null);
assert.equal(parseIncoming(ev({ message: { conversationId: "c1", direction: "incoming", text: null } })), null);

assert.deepEqual(parseRequest("raiox iPhone 15 128GB"), { kind: "query", query: "iPhone 15 128GB" });
assert.deepEqual(parseRequest("Raio-X: geladeira inverse"), { kind: "query", query: "geladeira inverse" });
assert.deepEqual(parseRequest("raiox https://www.magazineluiza.com.br/p/123/"), { kind: "link", url: "https://www.magazineluiza.com.br/p/123/" });
assert.deepEqual(parseRequest("raiox"), { kind: "empty" });
assert.deepEqual(parseRequest("airfryer 5l"), { kind: "query", query: "airfryer 5l" });

const reply = buildFoundReply({ name: "Air Fryer 5L", price: 399.9, productPath: "air-fryer/p/1", decision: "Espere.", headline: "Já custou menos.", detail: "Menor preço: R$ 349.", days: 90, now: new Date("2026-11-24T15:00:00Z") });
assert.match(reply, /^Raio-X Dopamina/);
assert.match(reply, /R\$\s399,90/);
assert.match(reply, /Espere\./);
assert.match(reply, /dopaminado\.com\.br\/produto\/air-fryer\/p\/1/);
assert.match(reply, /consultado em 24\/11/);
assert.ok(reply.includes(SIGNATURE) && reply.includes(DISCLAIMER));
const cm = (c = {}, over = {}) => ({ id: "ev2", event: "comment.received", comment: { id: "cm1", postId: "zp1", platformPostId: "ig1", platform: "instagram", text: "raiox airfryer 5l", isReply: false, author: { id: "u9", isOwnAccount: false }, ...c }, account: { accountId: "a1" }, ...over });
assert.deepEqual(parseComment(cm()), { eventId: "ev2", postId: "ig1", commentId: "cm1", accountId: "a1", authorId: "u9", text: "raiox airfryer 5l" });
assert.equal(parseComment(cm({ text: "Amei! 😍" })), null);
assert.equal(parseComment(cm({ isReply: true })), null);
assert.equal(parseComment(cm({ author: { id: "u9", isOwnAccount: true } })), null);
assert.equal(parseComment(cm({ platform: "youtube" })), null);
assert.equal(parseComment(cm({}, { event: "message.received" })), null);
assert.equal(parseBrl("1500"), 1500);
assert.equal(parseBrl("1.500"), 1500);
assert.equal(parseBrl("R$ 1.500,90"), 1500.9);
assert.equal(parseBrl("299,90"), 299.9);
assert.equal(parseBrl("sem número"), null);
assert.deepEqual(parseCommand("avisar"), { kind: "watch", target: null });
assert.deepEqual(parseCommand("Me avisa 1.500"), { kind: "watch", target: 1500 });
assert.deepEqual(parseCommand("meta R$ 299,90"), { kind: "watch", target: 299.9 });
assert.deepEqual(parseCommand("parar"), { kind: "stop" });
assert.equal(parseCommand("raiox avisar geladeira"), null);
assert.equal(parseCommand("avisar quando o preço da geladeira inverse de 500 litros cair bastante"), null);
assert.equal(defaultTarget(399.9), 379);
const t = buildTargetReply({ name: "Air Fryer", price: 349, target: 350, productPath: "p/1", decision: "Pode comprar.", headline: "h", detail: "", days: 30, now: new Date("2026-11-24T15:00:00Z") });
assert.match(t, /Alerta de preço: chegou na sua meta de R\$\s350,00/);
assert.ok(t.includes(SIGNATURE) && t.includes(DISCLAIMER));
assert.equal(isGreeting("Oi"), true);
assert.equal(isGreeting("Olá, tudo bem?"), true);
assert.equal(isGreeting("bom dia"), true);
assert.equal(isGreeting("ajuda"), true);
assert.equal(isGreeting("oi geladeira brastemp 400l"), false);
assert.equal(isGreeting("iphone 15"), false);
assert.deepEqual(parseRequest("oi"), { kind: "empty" });
assert.deepEqual(parseRequest("raiox ajuda"), { kind: "empty" });
assert.deepEqual(parseRequest("opa fone bluetooth"), { kind: "query", query: "opa fone bluetooth" });
assert.match(askMessage(), /raiox airfryer 5l/);
assert.match(askMessage(), /avisar/);
assert.match(alertHint("Espere."), /Vale esperar\. Responda avisar/);
assert.match(alertHint("Pode comprar."), /Responda: avisar/);
const esp = buildFoundReply({ name: "X", price: 10, productPath: "p/1", decision: "Espere.", headline: "h", detail: "", days: 30 });
assert.match(esp, /Vale esperar\. Responda avisar/);
assert.ok(esp.indexOf("Responda avisar") < esp.indexOf(SIGNATURE));
const sem = buildFoundReply({ name: "X", price: 10, productPath: null, decision: "Pode comprar.", headline: "h", detail: "", days: 30 });
assert.doesNotMatch(sem, /avisar/);
assert.doesNotMatch(t, /avisar/);
assert.equal(isExplicit("raiox airfryer"), true);
assert.equal(isExplicit("olha https://loja.com.br/p/1"), true);
assert.equal(isExplicit("kkk muito bom"), false);
assert.equal(isStoryReply({ message: { metadata: { replyTo: { story: { id: "1" } } } } }), true);
assert.equal(isStoryReply({ message: { attachments: [{ originalType: "ig_story" }] } }), true);
assert.equal(isStoryReply({ message: { text: "story do dia", metadata: {} } }), false);
assert.equal(isStoryReply({}), false);
assert.equal(parseIncoming(ev({ message: { conversationId: "c1", direction: "incoming", text: "airfryer 5l", sender: { id: "u1" }, metadata: { story: true } } }))?.storyReply, true);
assert.equal(parseIncoming(ev())?.storyReply, false);
